<?php

declare(strict_types=1);

namespace Wob\Library\Infrastructure\Hashing;

use stdClass;
use Wob\Library\Domain\Service\ContentHasher;
use Wob\Shared\Domain\Exception\InvariantViolation;

/**
 * A byte-for-byte port of fnv() and stable() from the client core/releases.js.
 *
 * "Close enough" is not a thing here. The fingerprint decides whether a saved
 * run still belongs to the level it was recorded on; if PHP and JavaScript
 * disagree by one character, every record the server accepts is a record the
 * client considers stale, and the whole point of versioning content evaporates.
 * Hence the golden vectors in tests/Fixtures/content-hashes.json, generated by
 * running the real client code over the shipped library.
 *
 * Three details are easy to get wrong and all three are load-bearing:
 *
 *  1. charCodeAt() walks UTF-16 code units, not bytes. A Cyrillic level title
 *     hashed byte by byte gives a different answer, and every built-in level has
 *     one. So the canonical string is converted to UTF-16 before folding.
 *  2. Math.imul is a 32-bit multiply that wraps. PHP integers are 64-bit, so
 *     every step is masked back down.
 *  3. JSON.stringify and json_encode disagree about slashes, non-ASCII and
 *     floats. The number and string formatting below follows the JavaScript
 *     rules, not the PHP defaults.
 */
final class Fnv1aContentHasher implements ContentHasher
{
    private const OFFSET_BASIS = 2166136261;
    private const PRIME = 16777619;
    private const MASK = 0xFFFFFFFF;

    /** @param array<string, mixed>|object $content */
    public function hash(array|object $content): string
    {
        return $this->fnv1a($this->canonicalise($content));
    }

    /** Exposed for tests and for debugging a mismatch: seeing the string matters. */
    public function canonicalise(mixed $value): string
    {
        if ($value === null || is_bool($value) || is_int($value) || is_float($value) || is_string($value)) {
            return $this->scalar($value);
        }

        if (is_array($value)) {
            return array_is_list($value)
                ? "[" . implode(",", array_map($this->canonicalise(...), $value)) . "]"
                : $this->object($value);
        }

        if ($value instanceof stdClass) {
            return $this->object(get_object_vars($value));
        }

        if (is_object($value) && method_exists($value, "jsonSerialize")) {
            return $this->canonicalise($value->jsonSerialize());
        }

        throw InvariantViolation::because("Cannot fingerprint a value of type " . get_debug_type($value));
    }

    /** @param array<array-key, mixed> $members */
    private function object(array $members): string
    {
        $keys = array_map(strval(...), array_keys($members));

        // JavaScript sorts by UTF-16 code unit; PHP string comparison sorts by
        // UTF-8 byte. They agree on ASCII and disagree above U+FFFF, so the
        // comparison is done on the same units JavaScript uses.
        usort($keys, fn (string $a, string $b): int => $this->compareUtf16($a, $b));

        $parts = [];

        foreach ($keys as $key) {
            $parts[] = $this->string($key) . ":" . $this->canonicalise($members[$key]);
        }

        return "{" . implode(",", $parts) . "}";
    }

    private function scalar(null|bool|int|float|string $value): string
    {
        return match (true) {
            $value === null => "null",
            is_bool($value) => $value ? "true" : "false",
            is_string($value) => $this->string($value),
            default => $this->number($value),
        };
    }

    /** JSON.stringify leaves slashes and non-ASCII alone; json_encode escapes both by default. */
    private function string(string $value): string
    {
        $encoded = json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);

        return $encoded;
    }

    private function number(int|float $value): string
    {
        if (is_int($value)) {
            return (string) $value;
        }

        // JSON.stringify writes NaN and Infinity as null.
        if (is_nan($value) || is_infinite($value)) {
            return "null";
        }

        // 1800.0 prints as "1800" in JavaScript, and "-0" prints as "0".
        if ($value === floor($value) && abs($value) < 1e21) {
            return $value === 0.0 ? "0" : sprintf("%.0f", $value);
        }

        // serialize_precision = -1 (the default since PHP 7.1) gives the same
        // shortest round-trip form JavaScript uses. Only the exponent spelling
        // differs: PHP writes 1.0e+21 where JavaScript writes 1e+21.
        $encoded = json_encode($value, JSON_THROW_ON_ERROR);

        return str_replace(".0e", "e", $encoded);
    }

    private function fnv1a(string $canonical): string
    {
        $hash = self::OFFSET_BASIS;

        foreach ($this->utf16CodeUnits($canonical) as $unit) {
            $hash ^= $unit;
            $hash = ($hash * self::PRIME) & self::MASK;
        }

        return str_pad(dechex($hash & self::MASK), 8, "0", STR_PAD_LEFT);
    }

    /** @return list<int> */
    private function utf16CodeUnits(string $utf8): array
    {
        $utf16 = mb_convert_encoding($utf8, "UTF-16LE", "UTF-8");
        $units = unpack("v*", $utf16);

        return $units === false ? [] : array_values($units);
    }

    /**
     * Lexicographic, element by element, shorter-is-smaller only on a tie.
     *
     * Not `$a <=> $b` on the two arrays: PHP compares arrays by COUNT first, so
     * "id" would sort before "entities" purely for being shorter, and every
     * object with keys of differing length would serialise in the wrong order.
     * JavaScript compares code unit by code unit. This cost a whole afternoon
     * once; the level fixtures caught it, the scalar vectors did not, because
     * their keys happened to be the same length.
     */
    private function compareUtf16(string $a, string $b): int
    {
        $left = $this->utf16CodeUnits($a);
        $right = $this->utf16CodeUnits($b);
        $shared = min(count($left), count($right));

        for ($i = 0; $i < $shared; $i++) {
            if ($left[$i] !== $right[$i]) {
                return $left[$i] <=> $right[$i];
            }
        }

        return count($left) <=> count($right);
    }
}

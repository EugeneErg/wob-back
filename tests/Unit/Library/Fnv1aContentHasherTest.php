<?php

declare(strict_types=1);

namespace Wob\Tests\Unit\Library;

use PHPUnit\Framework\TestCase;
use stdClass;
use Wob\Library\Domain\Model\Chapter;
use Wob\Library\Domain\Model\Level;
use Wob\Library\Domain\Model\Story;
use Wob\Library\Domain\ValueObject\ChapterId;
use Wob\Library\Domain\ValueObject\Dimensions;
use Wob\Library\Domain\ValueObject\EntityPlacement;
use Wob\Library\Domain\ValueObject\Gravity;
use Wob\Library\Domain\ValueObject\LevelId;
use Wob\Library\Domain\ValueObject\MapNode;
use Wob\Library\Domain\ValueObject\NodeId;
use Wob\Library\Domain\ValueObject\OwnerId;
use Wob\Library\Domain\ValueObject\StoryId;
use Wob\Library\Infrastructure\Hashing\Fnv1aContentHasher;

/**
 * The PHP hasher against fingerprints produced by the real client code.
 *
 * tests/Fixtures/content-hashes.json is generated by tools/hashes.mjs, which
 * runs the actual fnv() and stable() from core/releases.js over the shipped
 * library. If this test fails, PHP and JavaScript disagree about what a level
 * IS, and every version check between them is meaningless: the server would
 * accept records the client considers stale, and stories would look edited the
 * moment they were uploaded.
 *
 * Regenerate with: node tools/hashes.mjs ../wob > tests/Fixtures/content-hashes.json
 */
final class Fnv1aContentHasherTest extends TestCase
{
    private Fnv1aContentHasher $hasher;

    private stdClass $library;

    /** @var array<string, array<string, string>> */
    private array $expected;

    protected function setUp(): void
    {
        $this->hasher = new Fnv1aContentHasher();
        $this->expected = json_decode(
            (string) file_get_contents(__DIR__ . '/../../Fixtures/content-hashes.json'),
            true,
            512,
            JSON_THROW_ON_ERROR,
        );
        $this->library = json_decode(
            (string) file_get_contents(__DIR__ . '/../../Fixtures/library.json'),
            false,
            512,
            JSON_THROW_ON_ERROR,
        );
    }

    /**
     * The canonical string first. When a hash mismatches, this is the test that
     * says why — comparing eight hex characters tells you nothing.
     */
    public function testCanonicalFormMatchesJsonStringify(): void
    {
        // Keys sorted, not in insertion order.
        self::assertSame('{"a":1,"b":[1,2]}', $this->hasher->canonicalise((object) ['b' => [1, 2], 'a' => 1]));

        // JavaScript has no integer type: a whole float prints without a point,
        // and negative zero prints as zero.
        self::assertSame('1800', $this->hasher->canonicalise(1800.0));
        self::assertSame('0', $this->hasher->canonicalise(-0.0));
        self::assertSame('0.35', $this->hasher->canonicalise(0.35));

        // Slashes and non-ASCII stay as they are, unlike json_encode by default.
        self::assertSame('"a/b"', $this->hasher->canonicalise('a/b'));
        self::assertSame('"Лунка"', $this->hasher->canonicalise('Лунка'));

        // The distinction a decoded PHP array cannot express on its own, and the
        // reason entity data is carried as stdClass everywhere.
        self::assertSame('[]', $this->hasher->canonicalise([]));
        self::assertSame('{}', $this->hasher->canonicalise(new stdClass()));
    }

    /**
     * Keys of different lengths, which is the case the scalar vectors missed.
     *
     * PHP compares arrays by count before content, so an earlier version of the
     * comparator sorted "id" ahead of "entities" for being shorter, and every
     * real level hashed wrong while every hand-written vector passed. Sorting is
     * asserted directly here rather than only through a fingerprint.
     */
    public function testKeysSortLexicographicallyAndNotByLength(): void
    {
        self::assertSame(
            '{"entities":3,"goal":2,"id":1}',
            $this->hasher->canonicalise((object) ['id' => 1, 'goal' => 2, 'entities' => 3]),
        );

        // A prefix sorts before the longer string that contains it.
        self::assertSame(
            '{"a":1,"aa":2,"b":3}',
            $this->hasher->canonicalise((object) ['b' => 3, 'aa' => 2, 'a' => 1]),
        );
    }

    public function testScalarVectorsMatchTheClient(): void
    {
        self::assertSame(
            $this->expected['scalars']['sorted-keys'],
            $this->hasher->hash((object) ['b' => [1, 2], 'a' => 1]),
        );
        self::assertSame($this->expected['scalars']['empty-object'], $this->hasher->hash(new stdClass()));

        // Cyrillic is the one that catches a byte-wise fold: charCodeAt walks
        // UTF-16 code units, and every built-in level has a Russian title.
        self::assertSame(
            $this->expected['scalars']['unicode'],
            $this->hasher->hash((object) ['t' => 'Лунка / "x"']),
        );
        self::assertSame(
            $this->expected['scalars']['floats'],
            $this->hasher->hash((object) ['x' => 0.1, 'y' => -1800.5, 'z' => 1e21]),
        );
    }

    public function testEveryBuiltInLevelHashesLikeTheClient(): void
    {
        foreach ($this->library->levels as $level) {
            $content = (object) [
                'id' => $level->id,
                'width' => $level->width,
                'height' => $level->height,
                'gravity' => $level->gravity,
                'goal' => $level->goal,
                'entities' => $level->entities,
            ];

            self::assertSame(
                $this->expected['levels'][$level->id],
                $this->hasher->hash($content),
                sprintf('Level %s disagrees with the client', $level->id),
            );
        }
    }

    /**
     * Chapter and story fingerprints, taken from the domain itself.
     *
     * The earlier version of this test rebuilt the JavaScript formula in PHP
     * and compared that against the fixture — which passed happily while
     * Chapter::hashableContent() drifted, because the domain was never called.
     * A parity test that reimplements the thing it is checking is not a parity
     * test. This one builds a real Story and asks it.
     */
    public function testTheDomainProducesTheSameChapterAndStoryHashesAsTheClient(): void
    {
        $hasher = new Fnv1aContentHasher();
        $story = $this->builtInStory();

        foreach ($this->library->chapters as $chapter) {
            self::assertSame(
                $this->expected['chapters'][$chapter->id],
                $story->chapterHash($hasher, $story->chapter(new ChapterId($chapter->id)))->value,
                sprintf('Chapter %s disagrees with the client', $chapter->id),
            );
        }

        self::assertSame(
            $this->expected['stories']['story-first'],
            $story->contentHash($hasher)->value,
            'The story fingerprint disagrees with the client',
        );
    }

    /**
     * Renaming is the case the whole placement of names exists for: the story
     * gets a new version, and the level nobody touched keeps its fingerprint —
     * so every record ever set on it survives a typo fix.
     */
    public function testRenamingALevelMovesTheChapterAndStoryButNotTheLevel(): void
    {
        $hasher = new Fnv1aContentHasher();
        $story = $this->builtInStory();

        $levelId = new LevelId('lvl-tower');
        $chapterId = new ChapterId('ch-basics');

        $levelBefore = $story->levelHash($hasher, $story->level($levelId))->value;
        $chapterBefore = $story->chapterHash($hasher, $story->chapter($chapterId))->value;
        $storyBefore = $story->contentHash($hasher)->value;

        $story->level($levelId)->rename('A completely different name');

        self::assertSame($levelBefore, $story->levelHash($hasher, $story->level($levelId))->value);
        self::assertNotSame($chapterBefore, $story->chapterHash($hasher, $story->chapter($chapterId))->value);
        self::assertNotSame($storyBefore, $story->contentHash($hasher)->value);
    }

    /** And one level up: renaming a chapter is a change to the story alone. */
    public function testRenamingAChapterMovesOnlyTheStory(): void
    {
        $hasher = new Fnv1aContentHasher();
        $story = $this->builtInStory();
        $chapterId = new ChapterId('ch-basics');

        $chapterBefore = $story->chapterHash($hasher, $story->chapter($chapterId))->value;
        $storyBefore = $story->contentHash($hasher)->value;

        $story->chapter($chapterId)->rename('Renamed chapter');

        self::assertSame($chapterBefore, $story->chapterHash($hasher, $story->chapter($chapterId))->value);
        self::assertNotSame($storyBefore, $story->contentHash($hasher)->value);
    }

    private function builtInStory(): Story
    {
        $levels = [];

        foreach ($this->library->levels as $raw) {
            $levels[] = new Level(
                new LevelId($raw->id),
                $raw->name,
                new Dimensions((int) $raw->width, (int) $raw->height),
                Gravity::fromArray((array) $raw->gravity),
                (int) $raw->goal,
                array_map(EntityPlacement::fromObject(...), $raw->entities),
            );
        }

        $chapters = [];

        foreach ($this->library->chapters as $raw) {
            $chapters[] = new Chapter(
                new ChapterId($raw->id),
                $raw->title,
                $raw->image ?? '',
                array_map(
                    static fn (stdClass $n): MapNode => new MapNode(
                        new NodeId($n->id ?? 'nd-' . $n->levelId),
                        new LevelId($n->levelId),
                        (float) $n->x,
                        (float) $n->y,
                        array_map(static fn (string $c): NodeId => new NodeId($c), $n->next ?? []),
                    ),
                    $raw->nodes,
                ),
            );
        }

        $storyRaw = $this->library->stories[0];

        return new Story(
            new StoryId($storyRaw->id),
            new OwnerId('3f2504e0-4f89-41d3-9a0c-0305e82c3301'),
            $storyRaw->title,
            $storyRaw->cover ?? '',
            $chapters,
            $levels,
        );
    }

    /**
     * The property that makes the tree worth having: touch one level and the
     * story fingerprint moves. Without it, an author could silently invalidate
     * every record by nudging a rock.
     */
    public function testChangingOneEntityChangesTheLevelHash(): void
    {
        $level = $this->library->levels[0];
        $content = (object) [
            'id' => $level->id,
            'width' => $level->width,
            'height' => $level->height,
            'gravity' => $level->gravity,
            'goal' => $level->goal,
            'entities' => $level->entities,
        ];

        $before = $this->hasher->hash($content);

        $moved = json_decode(json_encode($content, JSON_THROW_ON_ERROR), false, 512, JSON_THROW_ON_ERROR);
        $moved->entities[0]->data->smoothness = 0.36;

        self::assertNotSame($before, $this->hasher->hash($moved));
    }
}
